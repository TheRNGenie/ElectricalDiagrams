// Writes sketches.js: every sketch in sketches/ as text, so the app carries the kit's code itself.
//   node tools/gen-sketches.mjs
import fs from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
const out = {};
for (const n of fs.readdirSync(root + 'sketches').sort()) {
  const f = `${root}sketches/${n}/${n}.ino`;
  if (fs.existsSync(f)) out[n] = fs.readFileSync(f, 'utf8');
}
fs.writeFileSync(root + 'sketches.js', '// Generated by tools/gen-sketches.mjs from sketches/. The kit sketches, built into the app.\nwindow.SKETCHES = ' + JSON.stringify(out, null, 0) + ';\n');
console.log(Object.keys(out).length, 'sketches');
